def validate_pose_orientation(face: Any, target_pose: str) -> Tuple[bool, str]:
    """
    Validates head pose orientation using 5-point facial landmarks
    aligned with unmirrored frame coordinates.
    """
    if not hasattr(face, 'kps') or face.kps is None:
        return True, "Valid (No landmarks available)"

    kps = face.kps  # Landmarks: [left_eye, right_eye, nose, mouth_left, mouth_right]
    left_eye, right_eye, nose = kps[0], kps[1], kps[2]

    eye_distance = np.linalg.norm(right_eye - left_eye)
    if eye_distance == 0:
        return True, "Valid"

    eye_center = (left_eye + right_eye) / 2.0
    horizontal_offset = (nose[0] - eye_center[0]) / eye_distance
    vertical_offset = (nose[1] - eye_center[1]) / eye_distance

    if target_pose == "FRONT / CENTER":
        if abs(horizontal_offset) > 0.25:
            return False, "Please look straight at the camera."

    elif target_pose == "LOOK LEFT":
        if horizontal_offset < 0.08:
            return False, "Please turn your head slightly further to your LEFT."

    elif target_pose == "LOOK RIGHT":
        if horizontal_offset > -0.08:
            return False, "Please turn your head slightly further to your RIGHT."

    elif target_pose == "LOOK UP":
        if vertical_offset > 0.35:
            return False, "Please tilt your head slightly UPWARDS."

    elif target_pose == "LOOK DOWN":
        if vertical_offset < 0.65:
            return False, "Please tilt your head slightly DOWNWARDS."

    return True, "Pose Validated"


