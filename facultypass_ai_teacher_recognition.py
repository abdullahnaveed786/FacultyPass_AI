def identify_teacher_from_image(
    image_bgr: np.ndarray,
    threshold: float = 0.45
) -> Tuple[np.ndarray, List[Dict[str, Any]]]:
    """Identifies live faces against stored .pkl 5x512 matrices."""
    annotated_img = image_bgr.copy()
    faces = vision_engine.analyze_frame(image_bgr)
    json_results = []
    pose_names = ["Front", "Left", "Right", "Up", "Down"]

    if len(faces) == 0:
        print("[INFO] No faces detected in input frame.")
        return annotated_img, json_results

    db_items = list(faculty_db.db.values())
    if not db_items:
        print("[WARNING] Vector Database is empty! Register a teacher first.")
        return annotated_img, json_results

    for face in faces:
        bbox = face.bbox.astype(int)

        norm = np.linalg.norm(face.embedding)
        query_vector = (face.embedding / norm).reshape(1, -1) if norm > 0 else face.embedding.reshape(1, -1)

        best_teacher = None
        max_score = -1.0
        matched_pose_idx = -1

        for item in db_items:
            # FIX: Key updated to 'embedding_matrix' matching Cell 3 schema
            teacher_matrix = item["embedding_matrix"]  # Shape: (5, 512)

            similarities = cosine_similarity(query_vector, teacher_matrix)[0]
            highest_pose_idx = int(np.argmax(similarities))
            highest_pose_score = float(similarities[highest_pose_idx])

            if highest_pose_score > max_score:
                max_score = highest_pose_score
                best_teacher = item
                matched_pose_idx = highest_pose_idx

        if max_score >= threshold:
            teacher_id = best_teacher['teacher_id']
            teacher_name = best_teacher['name']
            matched_pose = pose_names[matched_pose_idx]
            label_text = f"{teacher_name} ({max_score*100:.1f}%) [{matched_pose}]"
            box_color = (0, 255, 0)
            status = "Recognized"
        else:
            teacher_id = "N/A"
            teacher_name = "Unknown Individual"
            matched_pose = "None"
            label_text = f"Unknown ({max_score*100:.1f}%)"
            box_color = (0, 0, 255)
            status = "Unknown"

        h, w, _ = annotated_img.shape
        xmin, ymin = max(0, bbox[0]), max(0, bbox[1])
        xmax, ymax = min(w, bbox[2]), min(h, bbox[3])

        cv2.rectangle(annotated_img, (xmin, ymin), (xmax, ymax), box_color, 2)
        (text_w, text_h), _ = cv2.getTextSize(label_text, cv2.FONT_HERSHEY_SIMPLEX, 0.5, 2)
        cv2.rectangle(annotated_img, (xmin, max(0, ymin - text_h - 10)), (xmin + text_w + 10, ymin), box_color, -1)
        cv2.putText(annotated_img, label_text, (xmin + 5, max(12, ymin - 5)), cv2.FONT_HERSHEY_SIMPLEX, 0.5, (255, 255, 255), 1)

        json_results.append({
            "teacher_id": teacher_id,
            "name": teacher_name,
            "status": status,
            "matched_pose": matched_pose,
            "similarity_score": round(float(max_score), 4),
            "confidence_percentage": f"{max_score*100:.2f}%",
            "bbox_coordinates": {"xmin": int(xmin), "ymin": int(ymin), "xmax": int(xmax), "ymax": int(ymax)},
            "timestamp": time.strftime("%Y-%m-%d %H:%M:%S")
        })

    return annotated_img, json_results

