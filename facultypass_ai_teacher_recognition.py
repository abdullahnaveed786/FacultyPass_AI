class VisionEngine:
    """
    InsightFace ArcFace Model Wrapper (buffalo_l backbone).
    Extracts 512-D normalized feature embeddings and facial landmarks.
    """
    def __init__(self, name: str = 'buffalo_l', ctx_id: int = -1, det_size: Tuple[int, int] = (640, 640)):
        print(f"[INFO] Initializing InsightFace ArcFace model zoo: '{name}'...")
        # ctx_id = -1 for CPU, 0 for GPU
        self.app = FaceAnalysis(name=name, providers=['CUDAExecutionProvider', 'CPUExecutionProvider'] if ctx_id >= 0 else ['CPUExecutionProvider'])
        self.app.prepare(ctx_id=ctx_id, det_size=det_size)
        print("[STATUS] Vision Engine initialized.")

    def analyze_frame(self, frame_bgr: np.ndarray) -> List[Any]:
        """Detects faces and returns face objects with embeddings & landmarks."""
        return self.app.get(frame_bgr)


