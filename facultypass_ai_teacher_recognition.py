class ProductionTeacherVectorDB:
    """
    Persistent Vector Database supporting 5x512 multi-pose matrices.
    Loads existing .pkl files without overriding old records.
    """
    def __init__(self, db_filepath: str = DB_FILEPATH, similarity_threshold: float = 0.50):
        self.filepath = db_filepath
        self.similarity_threshold = similarity_threshold
        self.db: Dict[str, Dict[str, Any]] = {}

        # Safe Load: Only loads existing data, NEVER creates a blank file on startup
        self.load_from_disk()

    def is_registered_id(self, teacher_id: str) -> bool:
        """Checks if a primary key ID already exists in DB."""
        return teacher_id in self.db

    def check_biometric_duplicate(self, new_pose_matrix: np.ndarray) -> Tuple[bool, Optional[Dict[str, Any]], float]:
        """Compares new 5x512 matrix against ALL stored matrices in DB."""
        if not self.db:
            return False, None, 0.0

        best_match_teacher = None
        highest_score = -1.0

        for existing_id, profile in self.db.items():
            stored_matrix = profile["embedding_matrix"]  # Shape: (5, 512)
            similarity_matrix = cosine_similarity(new_pose_matrix, stored_matrix)
            max_similarity = float(np.max(similarity_matrix))

            if max_similarity > highest_score:
                highest_score = max_similarity
                best_match_teacher = profile

        if highest_score >= self.similarity_threshold:
            return True, best_match_teacher, highest_score

        return False, None, highest_score

    def register_teacher_embeddings(
        self,
        teacher_id: str,
        name: str,
        department: str,
        embeddings: List[np.ndarray]
    ) -> bool:
        """
        Appends new record to memory and updates disk without losing existing records.
        """
        if len(embeddings) != 5:
            print(f"[ERROR] Registration failed for {name}: Expected 5 pose embeddings, got {len(embeddings)}.")
            return False

        normalized_poses = []
        for emb in embeddings:
            norm = np.linalg.norm(emb)
            if norm > 0:
                normalized_poses.append(emb / norm)
            else:
                normalized_poses.append(emb)

        new_pose_matrix = np.array(normalized_poses, dtype=np.float32)  # Shape: (5, 512)

        # 1. Primary Key Check
        if self.is_registered_id(teacher_id):
            print(f"[REJECTED] Primary Key Conflict: Teacher ID '{teacher_id}' already exists in DB.")
            return False

        # 2. Biometric Duplicate Check
        is_dup, matched_profile, score = self.check_biometric_duplicate(new_pose_matrix)
        if is_dup:
            print("\n" + "🚨 " * 12)
            print(f"[REGISTRATION BLOCKED] Biometric Duplicate Detected!")
            print(f" This face is already registered as: {matched_profile['name']} (ID: {matched_profile['teacher_id']})")
            print(f" Match Score: {score * 100:.2f}%")
            print("🚨 " * 12 + "\n")
            return False

        # 3. Add to local memory dictionary (preserves existing teachers)
        self.db[teacher_id] = {
            "teacher_id": teacher_id,
            "name": name,
            "department": department,
            "embedding_matrix": new_pose_matrix
        }

        # 4. Save updated dictionary to file
        self.save_to_disk()
        print(f"[SUCCESS] Registered & Saved: {name} ({teacher_id}) | Total Teachers in DB: {len(self.db)}")
        return True

    def save_to_disk(self):
        """Saves current database dictionary to disk."""
        try:
            with open(self.filepath, "wb") as f:
                pickle.dump(self.db, f)
            print(f"[DISK SAVE] Updated persistent file at: '{self.filepath}' ({len(self.db)} records saved)")
        except Exception as e:
            print(f"[ERROR] Disk save failed: {e}")

    def load_from_disk(self):
        """Loads database from .pkl file if present; otherwise leaves DB empty."""
        if os.path.exists(self.filepath):
            try:
                with open(self.filepath, "rb") as f:
                    self.db = pickle.load(f)
                print(f"[DISK LOAD] Existing file found! Loaded {len(self.db)} teacher records from '{self.filepath}'.")
            except Exception as e:
                print(f"[WARNING] Could not read database file: {e}")
                self.db = {}
        else:
            print(f"[DISK LOAD] No existing file found at '{self.filepath}'. A new file will be created upon first registration.")


